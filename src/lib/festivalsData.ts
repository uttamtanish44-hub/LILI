// Helper functions
export function getFestivalsForYear(year: number): FestivalInfo[] {
  return FESTIVALS_DATABASE.filter((f) => f.date.startsWith(`${year}-`)).sort((a, b) => a.date.localeCompare(b.date));
}

export function getFestivalsForMonth(year: number, month: number): FestivalInfo[] {
  const monthStr = String(month).padStart(2, '0');
  const prefix = `${year}-${monthStr}`;
  return FESTIVALS_DATABASE.filter((f) => f.date.startsWith(prefix)).sort((a, b) => a.date.localeCompare(b.date));
}

export function getFestivalOnDate(dateStr: string): FestivalInfo[] {
  return FESTIVALS_DATABASE.filter((f) => f.date === dateStr);
}

export function getDaysDifference(targetDateStr: string, fromDateStr?: string): number {
  let now: Date;
  if (fromDateStr) {
    const [fy, fm, fd] = fromDateStr.split('-').map(Number);
    now = new Date(fy, fm - 1, fd);
  } else {
    now = new Date();
  }
  now.setHours(0, 0, 0, 0);

  const [y, m, d] = targetDateStr.split('-').map(Number);
  const target = new Date(y, m - 1, d);
  target.setHours(0, 0, 0, 0);

  const diffTime = target.getTime() - now.getTime();
  return Math.round(diffTime / (1000 * 60 * 60 * 24));
}

export function getUpcomingFestivals(limit: number = 8, fromDateStr?: string): { festival: FestivalInfo; daysRemaining: number }[] {
  let currentYMD = fromDateStr;
  if (!currentYMD) {
    const now = new Date();
    currentYMD = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  }

  const upcoming = FESTIVALS_DATABASE.filter((f) => f.date >= currentYMD!)
    .sort((a, b) => a.date.localeCompare(b.date))
    .slice(0, limit)
    .map((festival) => ({
      festival,
      daysRemaining: getDaysDifference(festival.date, currentYMD),
    }));

  return upcoming;
}

export function getTodayFestivals(fromDateStr?: string): FestivalInfo[] {
  let currentYMD = fromDateStr;
  if (!currentYMD) {
    const now = new Date();
    currentYMD = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  }
  return getFestivalOnDate(currentYMD!);
}

export function searchFestivals(query: string): FestivalInfo[] {
  const q = query.toLowerCase().trim();
  if (!q) return FESTIVALS_DATABASE;

  return FESTIVALS_DATABASE.filter(
    (f) =>
      f.name.toLowerCase().includes(q) ||
      (f.nameHindi && f.nameHindi.toLowerCase().includes(q)) ||
      f.category.toLowerCase().includes(q) ||
      f.significance.toLowerCase().includes(q) ||
      f.traditions.toLowerCase().includes(q) ||
      f.dayOfWeek.toLowerCase().includes(q) ||
      f.date.includes(q)
  );
}

export function getNextMajorFestival(fromDateStr?: string): { festival: FestivalInfo; daysRemaining: number } | null {
  const upcoming = getUpcomingFestivals(20, fromDateStr);
  const major = upcoming.find((item) => item.festival.isMajor);
  return major || upcoming[0] || null;
}
